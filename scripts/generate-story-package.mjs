import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  generatedStoryContent,
  loadRegistry,
  loadStoryPackage,
} from './lib/story-package.mjs';

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const appDirectory = dirname(scriptDirectory);
const args = process.argv.slice(2);
const requestedStoryId = args[args.indexOf('--story') + 1]?.trim();
const all = args.includes('--all');
const check = args.includes('--check');
const validateOnly = args.includes('--validate');

if (!requestedStoryId && !all) {
  throw new Error('Use --story <id> or --all.');
}

const registry = await loadRegistry(appDirectory);
const entries = all
  ? registry.stories
  : registry.stories.filter((entry) => entry.storyId === requestedStoryId);
if (entries.length === 0) {
  throw new Error(`Unknown story: ${requestedStoryId}`);
}
const sources = [];
for (const entry of entries) {
  sources.push(await loadStoryPackage(appDirectory, entry));
}

if (validateOnly) {
  for (const source of sources) {
    console.log(
      `Valid ${source.story.storyId}: ${source.scenes.length} scenes, ${source.scenes.flatMap((scene) => scene.visuals).length} visuals, ${source.fallbacks.length} fallbacks`,
    );
  }
  process.exit(0);
}

function stableJson(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

function quote(value) {
  return JSON.stringify(value);
}

function packageData(source) {
  return {
    schemaVersion: 1,
    story: source.story,
    routeContext: source.routeContext,
    cast: source.cast,
    reportCopy: source.reportCopy,
    release: source.release,
    evaluation: source.evaluation,
    sourceDigest: source.digest,
  };
}

function renderAppRegistry(allSources) {
  const imports = [
    "import { buildStoryRuntimePackage, type StoryRuntimePackage } from './story-package';",
    "import type { GeneratedStoryContent, StoryPackageData } from './story-package-types';",
    "import { STORY_AUDIO_ASSETS_BY_ID, STORY_IMAGE_ASSETS_BY_ID } from './story-assets.generated';",
  ];
  const blocks = [];
  const rows = [];
  for (const source of allSources) {
    const safe = source.story.storyId.replace(/[^A-Za-z0-9]/g, '_');
    imports.push(
      `import content_${safe} from '../${source.story.slug}/generated-story-content.json';`,
      `import data_${safe} from '../${source.story.slug}/story-package.generated.json';`,
    );
    blocks.push(
      `const package_${safe} = buildStoryRuntimePackage({\n  generatedContent: content_${safe} as unknown as GeneratedStoryContent,\n  packageData: data_${safe} as unknown as StoryPackageData,\n  imageAssets: STORY_IMAGE_ASSETS_BY_ID[${quote(source.story.storyId)}] ?? {},\n  audioAssets: STORY_AUDIO_ASSETS_BY_ID[${quote(source.story.storyId)}] ?? {},\n});`,
    );
    rows.push(`  ${quote(source.story.storyId)}: package_${safe},`);
  }
  return `${[
    '// Generated by scripts/generate-story-package.mjs. Do not edit manually.',
    ...imports,
    '',
    ...blocks,
    '',
    'export const STORY_PACKAGES_BY_ID: Readonly<Record<string, StoryRuntimePackage>> = {',
    ...rows,
    '};',
    `export const DEFAULT_BETA_STORY_ID = ${quote(registry.defaultBetaStoryId)};`,
  ].join('\n')}\n`;
}

// Assets ship from `public/`, which Vite serves at the site root — so an
// asset registered at `assets/story/...` is fetched from `/story/...`.
function publicAssetUrl(relativePath) {
  return `/${relativePath.replace(/^assets\//, '')}`;
}

function renderAppAssets(allSources) {
  const lines = [
    '// Generated by scripts/generate-story-package.mjs. Do not edit manually.',
    "import type { AudioSource, ImageSource } from './media-source';",
    '',
    'export const STORY_IMAGE_ASSETS_BY_ID: Readonly<Record<string, Readonly<Record<string, ImageSource>>>> = {',
  ];
  for (const source of allSources) {
    lines.push(`  ${quote(source.story.storyId)}: {`);
    for (const [assetId, path] of Object.entries(source.assets.imageAssets)) {
      lines.push(`    ${quote(assetId)}: { uri: ${quote(publicAssetUrl(path))} },`);
    }
    lines.push('  },');
  }
  lines.push(
    '};',
    '',
    'export const STORY_AUDIO_ASSETS_BY_ID: Readonly<Record<string, Readonly<Record<string, AudioSource>>>> = {',
  );
  for (const source of allSources) {
    lines.push(`  ${quote(source.story.storyId)}: {`);
    for (const [assetId, path] of Object.entries(source.assets.audioAssets)) {
      lines.push(`    ${quote(assetId)}: { uri: ${quote(publicAssetUrl(path))} },`);
    }
    lines.push('  },');
  }
  lines.push('};');
  return `${lines.join('\n')}\n`;
}

const allSources = [];
for (const entry of registry.stories) {
  allSources.push(await loadStoryPackage(appDirectory, entry));
}

const outputs = [];
for (const source of sources) {
  const directory = join(
    appDirectory,
    'src',
    'entities',
    'story',
    source.story.slug,
  );
  outputs.push(
    [join(directory, 'generated-story-content.json'), stableJson(generatedStoryContent(source))],
    [join(directory, 'story-package.generated.json'), stableJson(packageData(source))],
  );
}
outputs.push(
  [join(appDirectory, 'src', 'entities', 'story', 'model', 'story-registry.generated.ts'), renderAppRegistry(allSources)],
  [join(appDirectory, 'src', 'entities', 'story', 'model', 'story-assets.generated.ts'), renderAppAssets(allSources)],
);

let stale = false;
for (const [path, content] of outputs) {
  if (check) {
    let existing = '';
    try {
      existing = await readFile(path, 'utf8');
    } catch {
      existing = '';
    }
    if (existing !== content) {
      stale = true;
      console.error(`Stale generated content: ${path}`);
    }
    continue;
  }
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, content, 'utf8');
  console.log(`Generated ${path}`);
}
if (stale) process.exitCode = 1;
